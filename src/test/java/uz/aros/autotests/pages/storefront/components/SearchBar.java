package uz.aros.autotests.pages.storefront.components;

import com.microsoft.playwright.Locator;
import com.microsoft.playwright.Page;
import com.microsoft.playwright.options.AriaRole;
import io.qameta.allure.Step;
import uz.aros.autotests.pages.storefront.CatalogPage;

/**
 * Строка поиска в шапке сайта — доступна с любой страницы витрины.
 *
 * <h2>Почему локатор именно такой</h2>
 * Поле поиска — обычный текстовый инпут в шапке, но у него оказался
 * НЕПОСТОЯННЫЙ текст placeholder: на главной странице он на английском
 * ("Enter the product name..."), а на странице каталога/результатов —
 * почему-то на узбекском ("Mahsulot nomini kiriting..."). Похоже на баг
 * самого сайта (два разных места монтируют одно и то же поле с разными
 * переводами), но для нас важнее другое: раз текст placeholder'а
 * непостоянен, использовать его как локатор нельзя — тест бы ломался в
 * зависимости от того, с какой страницы стартовал.
 *
 * <p>Вместо текста опираемся на структуру: поле поиска — единственный
 * {@code <input>} в шапке с атрибутом {@code placeholder} (сам текст
 * плейсхолдера неважен, важно лишь то, что атрибут вообще есть — у
 * остальных полей шапки его нет).
 *
 * <h2>Почему отправка — это Enter, а не клик по кнопке-лупе</h2>
 * Так и хотелось сделать: у поля есть своя кнопка отправки (иконка лупы).
 * На практике же клик по ней оказался НЕНАДЁЖНЫМ — эмпирически, живым
 * прогоном, было замечено, что один и тот же клик то запускает переход на
 * страницу каталога, то просто закрывает выпадающий список подсказок и
 * остаётся на месте (похоже на гонку между кликом и внутренним
 * ре-рендером React прямо во время набора текста). А вот нажатие Enter
 * прямо в поле сработало стабильно во всех проверках — плюс само по себе
 * закрывает список подсказок. Поэтому отправка сделана именно так.
 */
public class SearchBar {

    private final Page page;
    private final Locator input;

    public SearchBar(Page page) {
        this.page = page;
        Locator header = page.getByRole(AriaRole.BANNER);
        this.input = header.locator("input[placeholder]");
    }

    /**
     * Печатает запрос и отправляет поиск нажатием Enter — сайт переходит
     * на страницу каталога с результатами (`/filter?query=...`).
     *
     * <p>Переход происходит через клиентский роутинг (SPA), без полной
     * перезагрузки страницы — старое содержимое ещё какое-то время
     * остаётся в DOM, пока React не подменит его новым. Если сразу после
     * отправки начать проверять содержимое каталога, можно поймать этот
     * промежуточный кадр и по ошибке решить, что в выдаче "не те" товары
     * (или что она пуста, хотя просто ещё не успела загрузиться) — именно
     * так и происходило на практике, пока не появился явный
     * {@code page.waitForURL(...)} ниже: он ждёт, пока URL браузера
     * подтвердит, что переход на {@code /filter} действительно случился,
     * и только потом можно доверять содержимому страницы.
     */
    @Step("Искать: {query}")
    public CatalogPage search(String query) {
        input.click();
        input.fill(query);
        input.press("Enter");
        page.waitForURL(url -> url.contains("/filter"));
        return new CatalogPage(page).waitUntilLoaded();
    }
}
