package uz.aros.autotests.base;

import com.microsoft.playwright.Page;

/**
 * Родитель для всех классов паттерна Page Object (HomePage, SignInForm,
 * AdminLoginPage и т.д.).
 *
 * <p>Что такое Page Object простыми словами: это класс, который "прячет"
 * от теста детали разметки страницы (какие там селекторы, кнопки, поля) и
 * предоставляет тесту простые методы на языке пользователя — например,
 * {@code signInForm.signIn(phone, password)} вместо того, чтобы в самом
 * тесте писать "найди инпут с плейсхолдером +998, кликни, введи текст...".
 *
 * <p>Главная выгода: если дизайнеры/фронтендеры поменяют вёрстку страницы,
 * править нужно только один Page Object, а не десятки тестов, которые её
 * используют.
 *
 * <p>Сейчас класс хранит только {@link Page} — единственное, что нужно
 * любому Page Object'у, чтобы искать элементы на странице. Если в будущем
 * появятся общие для всех страниц действия (например, "дождаться закрытия
 * общего лоадера"), их место — здесь.
 */
public abstract class BasePage {

    protected final Page page;

    protected BasePage(Page page) {
        this.page = page;
    }
}
